"""gt: ground-truth worlds, small models trained on them, and how close they get to Bayes.

gt data [WORLD ...]           build the frozen pools (all worlds of the ladder if none given)
gt train WORLD [--shape ...]  train one model on one world
gt ladder                     every world in order, simplest first: data, then training (skips what is done)
gt show [--write]             one row per run: floor, excess over Bayes, uncertainty tracking; --write
                              regenerates GT-RUNS.md next to PLAN.md
gt plot                       loss curves against the Bayes floor, per run and for the ladder
gt compress RUN               every compression setting on a trained run, scored against exact Bayes
gt control RUN,RUN,...        what controls the damage: training exposure per symbol, tokens per parameter
gt seeds RUN,RUN,...          a compression experiment across training seeds: each seed, mean, between-seed SD
gt inside RUN                 Jacobian and logit lens, probes, UMAP trajectories by layer (base vs compressed)
gt smoke                      tiny pools and 60 steps per world: does everything run end to end?
"""

import argparse
import json
import shutil
import sys
import time
from pathlib import Path

from . import data as D
from . import priors as P

NOTES = Path(__file__).resolve().parents[3] / "GT-RUNS.md"


def say(msg):
    print(msg, flush=True)


def _runs():
    root = D.GT / "runs"
    return sorted(root.glob("*/config.json"), key=lambda p: p.stat().st_mtime) if root.exists() else []


def _rows():
    rows = []
    for cfg_path in _runs():
        d = cfg_path.parent
        cfg = json.loads(cfg_path.read_text())
        s = json.loads((d / "summary.json").read_text()) if (d / "summary.json").exists() else None
        last = None
        if s is None and (d / "trace.jsonl").exists():
            vals = [json.loads(l) for l in (d / "trace.jsonl").read_text().splitlines() if '"valid"' in l]
            last = vals[-1] if vals else None
        rows.append((d, cfg, s, last))
    return rows


def show(write: bool = False):
    lines = [
        "| run | world | params | tokens | floor (Bayes) | unigram | model | excess ± se | first token | 129–256 | entropy gap | tracking | within position | minutes | status |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for d, cfg, s, last in _rows():
        if cfg.get("experiment") == "E1 report":
            continue  # different summary; listed in GT.md (E1) and <GT>/report/
        c = s["final"] if s else (last["valid"] if last else None)
        if c is None:
            lines.append(f"| {d.name} | {cfg['world']} | | | | | | | | | | | | | started {cfg['started']} |")
            continue
        unigram = (
            s["unigram"]
            if s
            else json.loads((Path(cfg["data"]) / "MANIFEST.json").read_text())["unigram_nats_per_token"]
        )
        tokens = s["tokens"] if s else last["tokens"]
        lines.append(
            f"| {d.name} | {cfg['world']} | {cfg['parameters'] / 1e6:.1f}M | {tokens / 1e6:.0f}M | {c['bayes']:.3f} | {unigram:.3f} | "
            f"{c['nats']:.3f} | {c['excess']:.4f} ± {c['excess_se']:.4f} | {c['excess_by_band']['1-1']:+.3f} | "
            f"{c['excess_by_band']['129-256']:+.4f} | {c['entropy_gap']:+.3f} | {c['tracking']:.2f} | {c['tracking_within']:.2f} | "
            f"{(s['train_seconds'] / 60 if s else float('nan')):.1f} | {'done ' + s['finished'] if s else 'running'} |"
        )
    table = "\n".join(lines)
    print(table)
    if write:
        worlds = P.worlds()
        head = [
            "# Ground-truth worlds: runs",
            "",
            "Generated by `pixi run gt-notes` from the run directories under `~/models/wu-runs/gt/runs`; do not edit by hand.",
            "Methods: GT.md. Columns:",
            "",
            "- **floor**: Bayes log loss (nats/token) on the frozen validation pool; **model**: the model's; **excess** = model − floor,",
            "  an unbiased estimate of KL(Bayes ‖ model), ± its standard error over 1,024 sequences.",
            "- **first token** and **129–256**: excess at the first position (prior only) and over the last half (much context).",
            "- **entropy gap**: model entropy − Bayes entropy (+ = too unsure). **tracking**: correlation of model and Bayes entropy",
            "  over positions; **within position**: the same after removing each position's mean (follows the prefix, not the clock).",
            "",
            "## Worlds",
            "",
            "| world | prior |",
            "|---|---|",
        ]
        head += [f"| {w} | {worlds[w].blurb} |" for w in P.ALL]
        head += ["", "## Runs", "", table, ""]
        head += _analysis_sections()
        head += [
            "## Reproducing a run",
            "",
            "Each run directory has `config.json` (world, shape, seed, schedule, sha256 of the data manifest, hashes of",
            "the `wu.gt` sources and `pixi.lock`), `trace.jsonl`, `summary.json`, `valid_model.npz` and `model/`.",
            "Pools are rebuilt bit-identically from fixed seeds (`pixi run gt-data`); `gt train` refuses changed pools.",
            "",
        ]
        NOTES.write_text("\n".join(head))
        print(f"wrote {NOTES}")


def _analysis_sections() -> list[str]:
    """Generated summaries of every compression, inside, control and seed analysis on disk."""
    from .stats import fmt

    out = []
    comp = sorted((D.GT / "compress").glob("*/report.json")) if (D.GT / "compress").exists() else []
    if comp:
        out += [
            "## Compression (gt compress)",
            "",
            "Damage = paired ΔKL to Bayes (nats/token); tracking AUC < 0.5 = surer where damaged. "
            "95% cluster-bootstrap intervals over validation sequences; one training seed per row "
            "(seed spread: next section). Full tables: `<GT>/compress/RUN/report.json`.",
            "",
        ]
        out += [
            "| run | setting | damage ΔKL | Δexcess new | Δexcess repeat | entropy gap | tracking AUC |",
            "|---|---|---|---|---|---|---|",
        ]
        for f in comp:
            rep = json.loads(f.read_text())
            for st, r in rep["settings"].items():
                if st == "base" or not isinstance(r.get("dkl"), dict):
                    continue
                out.append(
                    f"| {rep['run']} | {st} | {fmt(r['dkl'], 4, True)} | {fmt(r['d_excess_new'], 3, True)} | "
                    f"{fmt(r['d_excess_repeat'], 3, True)} | {fmt(r['entropy_gap'], 3, True)} | {fmt(r['tracking_auc'], 2)} |"
                )
        out.append("")
    seeds = sorted((D.GT / "seeds").glob("*.json")) if (D.GT / "seeds").exists() else []
    for f in seeds:
        rep = json.loads(f.read_text())
        out += [
            f"## Across training seeds: {f.stem} (gt seeds)",
            "",
            f"Runs: {', '.join(rep['runs'])}.",
            "",
            "| setting | metric | per seed | mean | between-seed SD |",
            "|---|---|---|---|---|",
        ]
        for st, ms in rep["settings"].items():
            for m, v in ms.items():
                out.append(
                    f"| {st} | {m} | "
                    + "; ".join(fmt(x, 3) for x in v["per_seed"])
                    + f" | {v['mean']:.3f} | {v['between_seed_sd']:.3f} |"
                )
        out.append("")
    ctl = D.GT / "control" / "report.json"
    if ctl.exists():
        rep = json.loads(ctl.read_text())
        out += [
            "## What controls the damage (gt control)",
            "",
            "Added prior error per symbol vs log10(exposure); "
            "pooled line vs one line per run (bootstrap over runs and symbols). Figures: `<GT>/control/`.",
            "",
            "| setting | slope per decade of exposure | R² one line | R² line per run |",
            "|---|---|---|---|",
        ]
        for st, c in rep["collapse"].items():
            out.append(
                f"| {st} | {fmt(c['slope_per_decade'], 3, True)} | {c['r2_pooled']:.2f} | {c['r2_separate_lines']:.2f} |"
            )
        out.append("")
    ins = sorted((D.GT / "inside").glob("*/report.json")) if (D.GT / "inside").exists() else []
    if ins:
        out += [
            "## Inside (gt inside)",
            "",
            "Figures and full per-layer readings with intervals: `<GT>/inside/RUN/`.",
            "",
        ]
        for f in ins:
            rep = json.loads(f.read_text())
            out.append(f"- {rep['run']}: settings {', '.join(rep['settings'])}, {rep['n_sequences']} sequences")
        out.append("")
    return out


def plot():
    import matplotlib

    from .train import BANDS

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    rows = [(d, cfg) for d, cfg, s, last in _rows() if (d / "trace.jsonl").exists() and not d.name.endswith("smoke")]
    if not rows:
        return say("no runs yet")
    fig, axes = plt.subplots(2, len(rows), figsize=(2.6 * len(rows), 4.6), squeeze=False, sharex=True)
    for j, (d, cfg) in enumerate(rows):
        tr = [json.loads(l) for l in (d / "trace.jsonl").read_text().splitlines()]
        tl = [(r["tokens"] / 1e6, r["loss"]) for r in tr if "loss" in r]
        va = [(r["tokens"] / 1e6, r["valid"]) for r in tr if "valid" in r and r["tokens"] > 0]
        top, bot = axes[0, j], axes[1, j]
        floor = va[-1][1]["bayes"] if va else None
        if tl:
            top.plot(*zip(*tl), color="0.75", lw=0.8, zorder=1)
        if va:
            top.plot([t for t, _ in va], [v["nats"] for _, v in va], color="black", lw=1.4, zorder=3)
            top.axhline(floor, color="C3", lw=1, ls="--", zorder=2)
            top.set_ylim(floor - 0.05, floor + 0.6)
            for (a, b), shade in zip(BANDS, ("0.8", "0.6", "0.4", "0.2", "black")):
                bot.plot(
                    [t for t, _ in va],
                    [max(v["excess_by_band"][f"{a + 1}-{b}"], 1e-4) for _, v in va],
                    color=shade,
                    lw=1.1,
                    label=f"pos {a + 1}–{b}",
                )
            bot.set_yscale("log")
            bot.set_ylim(1e-4, 3)
        top.set_title(cfg["world"], fontsize=9)
        for ax in (top, bot):
            ax.spines[["top", "right"]].set_visible(False)
            ax.tick_params(labelsize=7)
        bot.set_xlabel("tokens (M)", fontsize=7)
    axes[0, 0].set_ylabel("nats / token\n(dashed: Bayes floor)", fontsize=7)
    axes[1, 0].set_ylabel("excess over Bayes\n(nats, by position)", fontsize=7)
    axes[1, -1].legend(fontsize=6, frameon=False)
    fig.tight_layout()
    out = D.GT / "ladder.png"
    fig.savefig(out, dpi=150)
    say(f"wrote {out}")


def _parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="gt", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("data", help="build frozen pools")
    p.add_argument("worlds", nargs="*", help="default: every world of the ladder")
    p.add_argument("--force", action="store_true", help="rebuild even if the pool exists")

    train_p = sub.add_parser("train", help="train one model on one world")
    train_p.add_argument("world", choices=P.ALL)
    train_p.add_argument("--tag", default="", help="suffix of the run directory, e.g. long")
    train_p.add_argument("--force", action="store_true", help="retrain even if the run has finished")
    for p in (train_p, sub.add_parser("ladder", help="every ladder world in order")):
        p.add_argument("--shape", default="gt-6m")
        p.add_argument("--seed", type=int, default=0)
        p.add_argument("--steps", type=int, default=8000)
        p.add_argument("--batch-size", type=int, default=32)
        p.add_argument("--lr", type=float, default=1e-3)
        p.add_argument("--eval-every", type=int, default=500)

    p = sub.add_parser("compress", help="compress a trained run; score against Bayes")
    p.add_argument("run")
    p.add_argument("--settings", default=None, help="comma-separated; default: all 18")

    p = sub.add_parser("inside", help="lenses, probes and UMAP trajectories by layer, base vs compressed")
    p.add_argument("run")
    p.add_argument("--settings", default="gptq-2,wanda-50,rtn-3+emb")
    p.add_argument("--n", type=int, default=256, help="validation sequences")
    p.add_argument("--plot", action="store_true", help="only redraw layers.png from layer_points.npz")

    p = sub.add_parser("control", help="damage vs training exposure and tokens per parameter")
    p.add_argument("runs", help="comma-separated run names")
    p.add_argument("--settings", default="rtn-3,gptq-2,wanda-50,rtn-3+emb")

    p = sub.add_parser("seeds", help="one compression experiment across training seeds")
    p.add_argument("runs", help="comma-separated run names: the same experiment, different seeds")
    p.add_argument("--settings", default=None)

    p = sub.add_parser("show", help="one row per run")
    p.add_argument("--write", action="store_true", help="regenerate GT-RUNS.md")
    sub.add_parser("plot", help="loss curves against the Bayes floor")
    sub.add_parser("figures", help="summary figures with intervals and scaling fits (no GPU)")
    sub.add_parser("poster", help="four claims, one figure each, and poster.canvas (no GPU)")
    p = sub.add_parser("report-train", help="E1: train a Zipf model that also reports confidence in its guess")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--steps", type=int, default=32000)
    p.add_argument("--eval-every", type=int, default=2000)
    p.add_argument("--tag", default="long")
    p = sub.add_parser("report", help="E1: does the confidence report follow the guess after compression?")
    p.add_argument("run")
    p.add_argument("--settings", default="gptq-3,rtn-3,rtn-3+emb,gptq-2,magnitude-50,wanda-50,wanda-2:4,rtn-2")
    sub.add_parser("smoke", help="every world end to end on tiny pools")
    return ap


def _csv(text: str | None) -> list[str] | None:
    return [t for t in text.split(",") if t] if text else None


def cmd_data(args):
    for w in args.worlds or P.LADDER:
        if (D.data_dir(w) / "MANIFEST.json").exists() and not args.force:
            say(f"[gt data] {w}: exists ({D.data_dir(w)})")
        else:
            D.build(w, say=say)


def cmd_train(args):
    from .train import run_dir, train

    done = run_dir(args.world, args.shape, args.seed, args.tag) / "summary.json"
    if done.exists() and not args.force:
        return say(f"[gt train] {done.parent.name}: done already (--force to retrain)")
    train(
        args.world,
        args.shape,
        args.seed,
        args.steps,
        args.batch_size,
        args.lr,
        eval_every=args.eval_every,
        tag=args.tag,
        say=say,
    )


def cmd_ladder(args):
    from .train import run_dir, train

    for w in P.LADDER:
        if not (D.data_dir(w) / "MANIFEST.json").exists():
            D.build(w, say=say)
        if (run_dir(w, args.shape, args.seed) / "summary.json").exists():
            say(f"[gt ladder] {w}: done already")
            continue
        train(w, args.shape, args.seed, args.steps, args.batch_size, args.lr, eval_every=args.eval_every, say=say)
    show(write=True)
    plot()


def cmd_compress(args):
    from . import compress

    compress.run(args.run, _csv(args.settings) or compress.SETTINGS, say=say)


def cmd_inside(args):
    from . import inside

    if args.plot:
        return inside.plot_layers(D.GT / "inside" / args.run, args.run)
    inside.run(args.run, _csv(args.settings) or [], n=args.n, say=say)


def cmd_control(args):
    from . import control

    control.run(_csv(args.runs), _csv(args.settings), say=say)


def cmd_seeds(args):
    from . import control

    runs = _csv(args.runs)
    res = control.across_seeds(runs, _csv(args.settings), say=say)
    out = D.GT / "seeds" / f"{runs[0].replace('-s0', '')}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"runs": runs, "settings": res}, indent=1))
    say(f"wrote {out}")


def cmd_smoke(args):
    from .train import train

    t0 = time.time()
    for w in P.LADDER:
        D.build(w, n_train=2000, n_valid=32, tag="smoke", say=say)
        train(w, "gt-1m", 0, steps=60, batch_size=16, eval_every=30, tag="smoke", data_tag="smoke", say=say)
    for d in [*(D.GT / "runs").glob("*-smoke"), *(D.GT / "data").glob("*-smoke")]:
        shutil.rmtree(d)
    say(f"[gt smoke] every world ran end to end in {time.time() - t0:.0f}s (smoke pools and runs removed)")


def main(argv=None):
    args = _parser().parse_args(argv)
    commands = {
        "data": cmd_data,
        "train": cmd_train,
        "ladder": cmd_ladder,
        "compress": cmd_compress,
        "inside": cmd_inside,
        "control": cmd_control,
        "seeds": cmd_seeds,
        "smoke": cmd_smoke,
        "show": lambda a: show(a.write),
        "figures": lambda a: __import__("wu.gt.figures", fromlist=["run"]).run(say=say),
        "poster": lambda a: __import__("wu.gt.poster", fromlist=["run"]).run(say=say),
        "report-train": lambda a: __import__("wu.gt.report", fromlist=["train"]).train(
            seed=a.seed, steps=a.steps, eval_every=a.eval_every, tag=a.tag, say=say
        ),
        "report": lambda a: __import__("wu.gt.report", fromlist=["run"]).run(a.run, _csv(a.settings), say=say),
        "plot": lambda a: plot(),
    }
    commands[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
